import math
import numpy as np

SC, W, H, OY = 0.48, 480, 576, -20


def cubic(p0, p1, p2, p3):
    ln = math.dist(p0, p1) + math.dist(p1, p2) + math.dist(p2, p3)
    n = max(6, math.ceil(ln * SC / 1.2))
    t = np.linspace(0, 1, n + 1)[:, None]
    u = 1 - t
    p = np.array([p0, p1, p2, p3], float)
    pts = u ** 3 * p[0] + 3 * u * u * t * p[1] + 3 * u * t * t * p[2] + t ** 3 * p[3]
    return np.stack([pts[:, 0] * SC, (pts[:, 1] + OY) * SC], 1)


def arc(cx, cy, r, a0, a1):
    n = max(8, math.ceil(abs(a1 - a0) * r * SC / 1.2))
    a = np.linspace(a0, a1, n + 1)
    return np.stack([(cx + r * np.cos(a)) * SC, (cy + r * np.sin(a) + OY) * SC], 1)


def mx(p):
    return [1000 - p[0], p[1]]


def chain(*segs):
    out = None
    for s in segs:
        pts = cubic(*s)
        out = pts if out is None else np.vstack([out, pts[1:]])
    return out


